export function getLanguage(code: string): Language {
  return (
    SUPPORTED_LANGUAGES.find((lang) => lang.code === code) ||
    SUPPORTED_LANGUAGES.find((lang) => lang.code.startsWith(code.slice(0, 2))) ||
    SUPPORTED_LANGUAGES[0]
  );
}

export function searchLanguages(query: string, regionFilter?: string): Language[] {
  const q = query.trim().toLowerCase();
  return SUPPORTED_LANGUAGES.filter((lang) => {
    const matchesRegion = !regionFilter || regionFilter === 'All' || lang.region === regionFilter;
    const matchesQuery =
      !q ||
      lang.name.toLowerCase().includes(q) ||
      lang.nativeName.toLowerCase().includes(q) ||
      lang.code.toLowerCase().includes(q) ||
      lang.greeting.toLowerCase().includes(q);

    return matchesRegion && matchesQuery;
  });
}
